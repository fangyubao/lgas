/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  static uint32_t ontime_start = 0;
  uint8_t sys_status = STARTUP  ;
	uint8_t fail_n = 0U, sys_fail = 0U;
	char sys_fail_buf[64];
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DAC_Init();

#if 0
  MX_RTC_Init();
#else
  /* USB bring-up on empty board: skip RTC/LSE path temporarily. */
#endif
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_UART4_Init();
  MX_USART1_UART_Init();
  MX_USART2_UART_Init();
  MX_USART3_UART_Init();
  MX_USB_DEVICE_Init();
  modbus_master_init();
  modbus_master_h2_init();
  /* USER CODE BEGIN 2 */
	uart_startReceiveIT(UART_PORT_UART4);
#if 1
  rtc_init();
#else
  /* USB bring-up on empty board: skip RTC/LSE path temporarily. */
#endif
  if (DAC_OutputInit() != 0U)
  {
      Error_Handler();
  }
  pump_init();
  fan_init();
  dgusii_init(dgusii_HMI_task,NULL);
  //pump_set_strength(70);
  //app_mem_init();
  //loop_profiler_init(1000U);
  if(usb_task_init()!=0)
  {
      Error_Handler();
  }
	HMI_Powerstatus(TRUE);
  PowerOn_setTime(0);
  ontime_start = PowerOn_getTime();
  HAL_Delay(1000);
	uart_sendData(DGUSII_UART_PORT, HMI_TEXT_INITING_GBK, HMI_TEXT_INITING_GBK_LEN, DGUSII_TX_TIMEOUT_MS);
  HAL_Delay(1000);
  uart_sendData(DGUSII_UART_PORT, HMI_SCREEN_LIGHT, HMIHMI_SCREEN_LIGHT_LEN, DGUSII_TX_TIMEOUT_MS);

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */
    switch (sys_status)
    {
    case STARTUP:
      fan_set_speed(100);
	    HAL_Delay(100);
      uart_sendData(DGUSII_UART_PORT, HMI_CLOSE_TOUCH, HMI_CLOSE_TOUCH_LEN, DGUSII_TX_TIMEOUT_MS);
      HAL_Delay(100);
      if ((sys_fail=start_task_run()) == 0U)
      {
        sys_status = WARNUP;
        uart_sendData(DGUSII_UART_PORT, HMI_TEXT_PREHEAT_GBK, HMI_TEXT_PREHEAT_GBK_LEN, DGUSII_TX_TIMEOUT_MS);
      }
      else
      {
        uint8_t *opentofail = (uint8_t*)HMI_TEXT_INIT_ERR_ID_GBK;
        static const uint8_t hex_digit[] = "0123456789ABCDEF";
        opentofail[HMI_TEXT_INIT_ERR_ID_GBK_LEN-2] = hex_digit[(sys_fail >> 4) & 0x0FU];
        opentofail[HMI_TEXT_INIT_ERR_ID_GBK_LEN-1] = hex_digit[sys_fail & 0x0FU];
        uart_sendData(DGUSII_UART_PORT, opentofail, HMI_TEXT_INIT_ERR_ID_GBK_LEN, DGUSII_TX_TIMEOUT_MS);
				sprintf(sys_fail_buf,"init fail=%x,fail num=%d\r\n",sys_fail,fail_n);
				usb_cdc_send_packet((uint8_t *)sys_fail_buf, (uint16_t)strlen(sys_fail_buf));
        #ifdef HW_VERIGY
				fail_n += 1;
        sys_status = STOP;
        #else
        
        sys_status = WARNUP;
        #endif
      }
      break;

    case WARNUP:
      if(PowerOn_getTime()-ontime_start<=WARNMIN*1000)
        break;
      if((sys_fail=start_task_readbase()) == 0U)
      {	
        sys_status = RUNING;
      }else{
				uint8_t *opentofail = (uint8_t*)HMI_TEXT_INIT_ERR_ID_GBK;
        static const uint8_t hex_digit[] = "0123456789ABCDEF";
        opentofail[HMI_TEXT_INIT_ERR_ID_GBK_LEN-2] = hex_digit[(sys_fail >> 4) & 0x0FU];
        opentofail[HMI_TEXT_INIT_ERR_ID_GBK_LEN-1] = hex_digit[sys_fail & 0x0FU];
        uart_sendData(DGUSII_UART_PORT, opentofail, HMI_TEXT_INIT_ERR_ID_GBK_LEN, DGUSII_TX_TIMEOUT_MS);
				sprintf(sys_fail_buf,"init fail=%x,fail num=%d\r\n",sys_fail,fail_n);
				usb_cdc_send_packet((uint8_t *)sys_fail_buf, (uint16_t)strlen(sys_fail_buf));
        #ifdef HW_VERIGY
				fail_n += 1;
        sys_status = STOP;
        #else
        
        sys_status = WARNUP;
        #endif
			}
			uart_sendData(DGUSII_UART_PORT, HMI_OPEN_TOUCH, HMI_OPEN_TOUCH_LEN, DGUSII_TX_TIMEOUT_MS);
      HAL_Delay(100);
      uart_sendData(DGUSII_UART_PORT, HMI_INTO_MENU, HMI_INTO_MENU_LEN, DGUSII_TX_TIMEOUT_MS);
			HAL_Delay(100);
      solenoid_set_duty(100);
    break;
    case RUNING:
      //loop_profiler_begin();
      app_tasks_run_running();
      //loop_profiler_end();
      break;

    case STOP:
      app_tasks_run_stop();
      break;

    default:
      break;
    
    }

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

